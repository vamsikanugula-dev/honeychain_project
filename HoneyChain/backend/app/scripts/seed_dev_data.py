"""Seed a development database with one account per role and a demo cluster.

**DEVELOPMENT ONLY.** The credentials it prints are published in the README so a
reviewer can sign in and explore every workspace. They must never be used, or
exist, in a production deployment — the script refuses to run when the
environment is production, and every row it writes is audited like any other
change.

What it creates (idempotently — re-running reports `[exists]` and changes
nothing):

| Role | Email | Notes |
| --- | --- | --- |
| `ADMIN` | `admin@honeychain.example.com` | Platform administration |
| `KVIC_OFFICER` | `kvic@honeychain.example.com` | Beekeeper review, clusters |
| `BEEKEEPER` | `beekeeper@honeychain.example.com` | Apiary record, verified, in the demo cluster |
| `CONSUMER` | `consumer@honeychain.example.com` | Self-service profile only |

It also registers one demo hive (`HIVE-GNT-00001`) for the beekeeper and one
ESP32-class device (`ESP32-GNT-0001`) attached to it, which starts OFFLINE. **No
telemetry is generated by this script** — readings only appear once the
simulator (or real hardware) sends them, and simulator readings are stored with
``source = SIMULATOR`` so they are never mistaken for real device data.

Plus one KVIC cluster (`KVIC-GNT-001`) with the beekeeper as a member, so the
directory, cluster and verification screens have something real to show.

Usage::

    python -m app.scripts.seed_dev_data
    python -m app.scripts.seed_dev_data --reset
"""

