def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Seed development data (DEVELOPMENT ONLY).")
    parser.add_argument(
        "--reset",
        action="store_true",
        help="Delete the seeded accounts and cluster instead of creating them.",
    )
    return parser.parse_args(argv)


def _ensure_accounts(session) -> dict[str, User]:
    """Create the fixture accounts that do not exist yet; return them by email."""
    users = UserRepository(session)
    created: dict[str, User] = {}

    for role, name, email, password, phone, state, district, organization in ACCOUNTS:
        existing = users.get_by_email(email)
        if existing is not None:
            print(f"  [exists]  {email} ({role.value})")
            created[email] = existing
            continue

        user = users.create_user(
            name=name,
            email=email,
            role=role,
            password_hash=hash_password(password),
            phone=phone,
            state=state,
            district=district,
            organization=organization,
        )
        print(f"  [created] {email} ({role.value})")
        created[email] = user

    session.commit()
    return created


def _ensure_cluster(session, *, actor: User):
    clusters = ClusterService(session)
    found, _total = clusters.list_clusters(search=CLUSTER.cluster_name, page=1, page_size=1)
    if found:
        print(f"  [exists]  cluster {found[0].cluster_code} — {found[0].cluster_name}")
        return found[0]

    # A cluster may already exist in the same district (created by an earlier
    # fixture or by hand). Reusing it keeps the development database free of
    # near-duplicate clusters.
    siblings, _total = clusters.list_clusters(
        district=CLUSTER.district, is_active=True, page=1, page_size=1
    )
    if siblings:
        print(
            f"  [reused]  cluster {siblings[0].cluster_code} — {siblings[0].cluster_name} "
            f"({CLUSTER.district})"
        )
        return siblings[0]

    cluster = clusters.create_cluster(CLUSTER, actor=actor)
    print(f"  [created] cluster {cluster.cluster_code} — {cluster.cluster_name}")
    return cluster


def _ensure_beekeeper(session, user: User):
    beekeepers = BeekeeperRepository(session)
    existing = beekeepers.get_by_user_id(user.id)
    if existing is not None:
        print(f"  [exists]  beekeeper {existing.beekeeper_code} for {user.email}")
        return existing

    beekeeper = BeekeeperService(session).create_for_user(user, BEEKEEPER_PROFILE)
    print(f"  [created] beekeeper {beekeeper.beekeeper_code} for {user.email}")
    return beekeeper


def _ensure_demo_hive(session, *, beekeeper, actor: User):
    """One hive for the seeded beekeeper so the registry is not empty (dev only)."""
    hives = HiveService(session)
    existing, _total = hives.list_hives(actor, page=1, page_size=1)
    if existing:
        print(f"  [exists]  hive {existing[0].hive_code} — {existing[0].village}")
        return existing[0]

    hive = hives.create(actor, DEMO_HIVE)
    print(f"  [created] hive {hive.hive_code} — {hive.village}, {hive.district}")
    return hive


def _ensure_demo_device(session, *, hive, actor: User):
    """One device attached to the demo hive, starting OFFLINE (it has not reported)."""
    devices = DeviceService(session)
    existing = devices.devices.get_by_device_id(DEMO_DEVICE_ID)
    if existing is not None:
        print(f"  [exists]  device {existing.device_id} on hive {existing.hive_id}")
        return existing

    device = devices.register(
        actor,
        DeviceCreate(
            device_id=DEMO_DEVICE_ID,
            device_name="Tenali field node 1",
            hive_id=hive.id,
            firmware_version="1.0.0",
        ),
    )
    print(
        f"  [created] device {device.device_id} on {hive.hive_code} "
        "(status OFFLINE until it reports)"
    )
    return device


def seed(session) -> int:
    print(BANNER)
    print("  HoneyChain development seed — DEVELOPMENT ONLY")
    print("  These credentials must never be used outside a local database.")
    print(BANNER)

    accounts = _ensure_accounts(session)
    admin = accounts["admin@honeychain.example.com"]
    officer = accounts["kvic@honeychain.example.com"]
    beekeeper_user = accounts["beekeeper@honeychain.example.com"]

    print()
    cluster = _ensure_cluster(session, actor=admin)
    beekeeper = _ensure_beekeeper(session, beekeeper_user)

    service = BeekeeperService(session)
    if beekeeper.kvic_cluster_id is None:
        service.assign_cluster(beekeeper.id, cluster.id, actor=officer)
        print(f"  [linked]  {beekeeper.beekeeper_code} → {cluster.cluster_code}")

    if beekeeper.verification_status != "VERIFIED":
        service.change_verification(
            beekeeper.id,
            status="VERIFIED",
            remarks="Development fixture: reviewed by the KVIC officer during seeding.",
            actor=officer,
        )
        print(f"  [verified] {beekeeper.beekeeper_code} → VERIFIED")

    print()
    hive = _ensure_demo_hive(session, beekeeper=beekeeper, actor=beekeeper_user)
    device = _ensure_demo_device(session, hive=hive, actor=beekeeper_user)

    print()
    print("Accounts (DEVELOPMENT ONLY):")
    for role, _name, email, password, *_rest in ACCOUNTS:
        print(f"  {role.value:13} {email:38} {password}")
    print(f"\nCluster: {cluster.cluster_code} — {cluster.cluster_name}")
    print(f"Hive:    {hive.hive_code} — {hive.village}, {hive.district} (owned by {beekeeper.beekeeper_code})")
    print(f"Device:  {device.device_id} — OFFLINE until telemetry arrives")
    print("\nNo telemetry is fabricated by this script. To see the monitoring screens")
    print("with data, run the simulator (every reading is stored as SIMULATOR):")
    print(f"  python -m app.scripts.hive_simulator --device {device.device_id} --transport http")
    print("Sign in at http://localhost:5173/login")
    print(BANNER)
    return 0


def reset(session) -> int:
    """Remove the seeded accounts and cluster (their rows cascade)."""
    print(BANNER)
    print("  HoneyChain development seed — removing fixtures")
    print(BANNER)

    users = UserRepository(session)
    for _role, _name, email, _password, *_rest in ACCOUNTS:
        user = users.get_by_email(email)
        if user is None:
            print(f"  [absent]  {email}")
            continue
        session.delete(user)
        print(f"  [deleted] {email}")

    clusters = ClusterService(session)
    found, _total = clusters.list_clusters(search=CLUSTER.cluster_name, page=1, page_size=10)
    for cluster in found:
        session.delete(cluster)
        print(f"  [deleted] cluster {cluster.cluster_code}")

    session.commit()
    return 0


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    settings = build_settings()
    configure_logging(settings)

    if settings.is_production:
        print(
            "Refusing to run: the development seed must never touch a production database.",
            file=sys.stderr,
        )
        return 2

    with SessionLocal() as session:
        return reset(session) if args.reset else seed(session)


if __name__ == "__main__":  # pragma: no cover - manual entry point
    raise SystemExit(main())
