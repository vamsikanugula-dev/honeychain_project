class VerificationChangeRequest(BaseModel):
    """``PATCH /api/v1/beekeepers/{id}/verification`` request body."""

    model_config = ConfigDict(extra="forbid")

    status: VerificationStatus
    remarks: str | None = Field(
        default=None,
        max_length=1000,
        description="Explanation recorded in the verification history and audit log.",
        examples=["Verified by KVIC officer after field visit"],
    )

    @field_validator("remarks")
    @classmethod
    def _clean_remarks(cls, value: str | None) -> str | None:
        if value is None:
            return None
        cleaned = " ".join(value.split())
        return cleaned or None

    @model_validator(mode="after")
    def _negative_decisions_need_a_reason(self) -> "VerificationChangeRequest":
        """Rejections and suspensions must be explained.

        A model-level check rather than a field one: a field validator does not
        run when the field is simply absent, which is exactly the case that
        matters here.
        """
        if self.status in (VerificationStatus.REJECTED, VerificationStatus.SUSPENDED):
            if not self.remarks or len(self.remarks) < 5:
                raise ValueError(
                    "Please provide a remark explaining this decision "
                    "(at least 5 characters)"
                )
        return self


class VerificationHistoryEntry(BaseModel):
    """One row of the append-only verification trail."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    previous_status: VerificationStatus | None = None
    new_status: VerificationStatus
    remarks: str | None = None
    changed_by_id: uuid.UUID | None = None
    changed_by_name: str | None = None
    changed_by_role: str | None = None
    changed_at: datetime


class BeekeeperDetail(BaseModel):
    """Beekeeper detail view: record plus its verification trail."""

    beekeeper: BeekeeperPublic
    verification_history: list[VerificationHistoryEntry] = Field(default_factory=list)
    allowed_next_statuses: list[VerificationStatus] = Field(default_factory=list)


