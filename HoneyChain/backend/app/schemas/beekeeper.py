"""Beekeeper schemas — registration, self-service, officer management, verification."""

from __future__ import annotations

import uuid
from datetime import date, datetime

from pydantic import BaseModel, ConfigDict, EmailStr, Field, field_validator, model_validator

from app.models.enums import VerificationStatus
from app.schemas.profile import ProfileLocation


class BeekeeperPractice(BaseModel):
    """Apiary practice details."""

    model_config = ConfigDict(extra="forbid")

    experience_years: int | None = Field(default=None, ge=0, le=90, examples=[5])
    bee_species: str | None = Field(
        default=None, max_length=80, examples=["Apis cerana indica"]
    )
    number_of_hives: int | None = Field(default=None, ge=0, le=100000, examples=[12])

    @field_validator("bee_species")
    @classmethod
    def _clean_species(cls, value: str | None) -> str | None:
        if value is None:
            return None
        cleaned = " ".join(value.split())
        return cleaned or None


class BeekeeperCreate(BeekeeperPractice, ProfileLocation):
    """Beekeeper details supplied during registration.

    Two fields are deliberately absent:

    * ``beekeeper_code`` — generated by the backend from a locked counter.
    * ``kvic_cluster_id`` — cluster membership is an organisational decision an
      officer makes after review, not something a public form can claim.

    ``extra="forbid"`` turns an attempt to send either into a 422 rather than a
    silently ignored field.
    """


class BeekeeperSelfUpdate(BeekeeperPractice, ProfileLocation):
    """What a beekeeper may change about their own record.

    Excludes ``kvic_cluster_id``, ``verification_status`` and
    ``beekeeper_code`` — those are officer- or system-controlled.
    """


class BeekeeperUpdate(BeekeeperSelfUpdate):
    """What an administrator or KVIC officer may change."""

    kvic_cluster_id: uuid.UUID | None = None


