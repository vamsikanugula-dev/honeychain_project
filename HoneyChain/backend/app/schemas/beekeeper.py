# --------------------------------------------------------------------------- #
# Projections
#
# These live in the schema layer because they are pure presentation: they turn a
# loaded ORM object into the shape a specific endpoint promises. Keeping them
# here means routes stay free of mapping code and every endpoint that returns a
# beekeeper describes it identically.
# --------------------------------------------------------------------------- #
def _cluster_block(beekeeper) -> dict | None:
    cluster = getattr(beekeeper, "cluster", None)
    if cluster is None:
        return None
    return {
        "id": cluster.id,
        "cluster_code": cluster.cluster_code,
        "cluster_name": cluster.cluster_name,
        "district": cluster.district,
        "is_active": cluster.is_active,
    }


def _owner_block(beekeeper) -> dict:
    user = beekeeper.user
    return {
        "id": user.id,
        "name": user.name,
        "email": user.email,
        "phone": user.phone,
        "is_active": user.is_active,
        "is_verified": user.is_verified,
        "last_login_at": user.last_login_at,
        "created_at": user.created_at,
    }


def to_beekeeper_public(beekeeper) -> BeekeeperPublic:
    """Full representation for a detail view."""
    cluster = getattr(beekeeper, "cluster", None)
    return BeekeeperPublic(
        id=beekeeper.id,
        beekeeper_code=beekeeper.beekeeper_code,
        experience_years=beekeeper.experience_years,
        bee_species=beekeeper.bee_species,
        number_of_hives=beekeeper.number_of_hives,
        village=beekeeper.village,
        mandal=beekeeper.mandal,
        district=beekeeper.district,
        state=beekeeper.state,
        pincode=beekeeper.pincode,
        registration_date=beekeeper.registration_date,
        verification_status=VerificationStatus(beekeeper.verification_status),
        verification_label=VerificationStatus(beekeeper.verification_status).label,
        verification_remarks=beekeeper.verification_remarks,
        verified_at=beekeeper.verified_at,
        created_at=beekeeper.created_at,
        updated_at=beekeeper.updated_at,
        user=BeekeeperOwnerInfo(**_owner_block(beekeeper)),
        cluster=BeekeeperClusterInfo(**_cluster_block(beekeeper)) if cluster else None,
    )


def to_beekeeper_list_item(beekeeper) -> BeekeeperListItem:
    """Compact row for directory tables.

    Carries the owner's name and email because an officer scanning the queue
    needs to identify people, not just UUIDs, but omits the audit fields that
    only the detail view shows.
    """
    user = beekeeper.user
    cluster = getattr(beekeeper, "cluster", None)
    return BeekeeperListItem(
        id=beekeeper.id,
        beekeeper_code=beekeeper.beekeeper_code,
        name=user.name,
        email=user.email,
        phone=user.phone,
        village=beekeeper.village,
        mandal=beekeeper.mandal,
        district=beekeeper.district,
        state=beekeeper.state,
        experience_years=beekeeper.experience_years,
        bee_species=beekeeper.bee_species,
        number_of_hives=beekeeper.number_of_hives,
        verification_status=VerificationStatus(beekeeper.verification_status),
        verification_label=VerificationStatus(beekeeper.verification_status).label,
        cluster_id=beekeeper.kvic_cluster_id,
        cluster_code=cluster.cluster_code if cluster else None,
        cluster_name=cluster.cluster_name if cluster else None,
        registration_date=beekeeper.registration_date,
        created_at=beekeeper.created_at,
    )


def to_beekeeper_detail(beekeeper) -> BeekeeperDetail:
    """Detail view plus the append-only verification trail."""
    current = VerificationStatus(beekeeper.verification_status)
    return BeekeeperDetail(
        beekeeper=to_beekeeper_public(beekeeper),
        verification_history=[
            VerificationHistoryEntry.model_validate(entry)
            for entry in beekeeper.verification_history
        ],
        allowed_next_statuses=VerificationStatus.allowed_transitions(current),
    )


